'use strict';
/* Собирает levels/*.json в js/levels.data.js — уровни остаются обычными JSON-файлами. */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'levels');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json'));

const levels = files.map((file) => {
  const raw = fs.readFileSync(path.join(dir, file), 'utf8');
  const level = JSON.parse(raw);
  level.sourceFile = file;
  return level;
}).sort((a, b) => a.order - b.order);

levels.forEach((l) => {
  if (!l.id || !l.station || !Array.isArray(l.targets)) {
    throw new Error('Некорректный уровень: ' + l.sourceFile);
  }
  if (!Array.isArray(l.controlPoints) || l.controlPoints.length < 3) {
    throw new Error('Нужно минимум 3 пункта привязки (controlPoints) в ' + l.sourceFile);
  }
  const ids = new Set();
  l.controlPoints.forEach((c) => {
    if (!c.id || !isFinite(c.x) || !isFinite(c.y) || !isFinite(c.z)) {
      throw new Error('Некорректный пункт привязки в ' + l.sourceFile);
    }
    if (ids.has(c.id)) throw new Error('Дублирующийся ID ' + c.id + ' в ' + l.sourceFile);
    ids.add(c.id);
  });
  l.targets.forEach((t) => {
    if (ids.has(t.id)) throw new Error('Дублирующийся ID ' + t.id + ' в ' + l.sourceFile);
    ids.add(t.id);
  });
  if (l.backsight && !l.controlPoints.some((c) => c.id === l.backsight.id)) {
    throw new Error('Задняя точка ' + l.backsight.id + ' отсутствует среди пунктов привязки в ' + l.sourceFile);
  }
});

const banner = '/* AUTO-GENERATED by tools/build-levels.js from levels/*.json — не редактировать вручную. */\n';
const body = 'window.GEO = window.GEO || {};\nwindow.GEO.LEVELS = ' + JSON.stringify(levels, null, 2) + ';\n';
fs.writeFileSync(path.join(root, 'js', 'levels.data.js'), banner + body, 'utf8');
console.log('levels.data.js: ' + levels.length + ' уровней (' + levels.map((l) => l.id).join(', ') + ')');
